// Package licenses finds the licence of every Go module linked into the binary, classifies it against the
// allow and deny lists (TESTPLAN LIC-01, LIC-03) and renders the NOTICE file (LIC-02).
package licenses

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

type Module struct {
	Path, Version, Dir string
	License            string // SPDX-like name, or "UNKNOWN"
	Text               string
}

// deny lists licence families that must never be linked or bundled (SPEC 17.9, TESTPLAN LIC-03).
var deny = []string{"GNU GENERAL PUBLIC LICENSE", "GNU AFFERO", "GNU LESSER GENERAL PUBLIC", "SERVER SIDE PUBLIC LICENSE", "BUSINESS SOURCE LICENSE", "ELASTIC LICENSE", "COMMONS CLAUSE", "REDIS SOURCE AVAILABLE", "RSAL"}

// Classify names the licence from its text; the order matters (Apache text mentions "copyright" like the others).
func Classify(text string) string {
	u := strings.Join(strings.Fields(strings.ToUpper(text)), " ") // line wrapping must not matter
	for _, d := range deny {
		if strings.Contains(u, d) {
			return "DENIED: " + d
		}
	}
	switch {
	case strings.Contains(u, "APACHE LICENSE") && strings.Contains(u, "VERSION 2.0"):
		return "Apache-2.0"
	case strings.Contains(u, "MOZILLA PUBLIC LICENSE"):
		return "MPL-2.0"
	case strings.Contains(u, "PERMISSION TO USE, COPY, MODIFY, AND/OR DISTRIBUTE THIS SOFTWARE") ||
		strings.Contains(u, "PERMISSION TO USE, COPY, MODIFY, AND DISTRIBUTE THIS SOFTWARE FOR ANY PURPOSE WITH OR WITHOUT FEE") ||
		strings.Contains(u, "ISC LICENSE"):
		return "ISC"
	case strings.Contains(u, "PERMISSION IS HEREBY GRANTED, FREE OF CHARGE") || strings.Contains(u, "MIT LICENSE"):
		return "MIT"
	case strings.Contains(u, "REDISTRIBUTION AND USE IN SOURCE AND BINARY FORMS") && strings.Contains(u, "NEITHER THE NAME"):
		return "BSD-3-Clause"
	case strings.Contains(u, "REDISTRIBUTION AND USE IN SOURCE AND BINARY FORMS"):
		return "BSD-2-Clause"
	}
	return "UNKNOWN"
}

// Allowed reports whether a classified licence may be linked.
func Allowed(l string) bool {
	switch l {
	case "MIT", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "ISC", "MPL-2.0":
		return true
	}
	return false
}

func goBin() string {
	if p := filepath.Join(runtime.GOROOT(), "bin", "go"); fileExists(p) {
		return p
	}
	return "go"
}

func fileExists(p string) bool { _, err := os.Stat(p); return err == nil }

// Linked returns the modules (other than the main one) that provide packages linked into ./cmd/tasklane.
func Linked(root string) ([]Module, error) {
	cmd := exec.Command(goBin(), "list", "-deps", "-f", "{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}|{{.Module.Main}}{{end}}", "./cmd/tasklane")
	cmd.Dir = root
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("go list: %v: %s", err, errb.String())
	}
	seen := map[string]bool{}
	var mods []Module
	for _, l := range strings.Split(strings.TrimSpace(out.String()), "\n") {
		f := strings.Split(l, "|")
		if len(f) != 4 || f[3] == "true" || seen[f[0]] {
			continue
		}
		seen[f[0]] = true
		m := Module{Path: f[0], Version: f[1], Dir: f[2], License: "UNKNOWN"}
		for _, name := range []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "LICENCE"} {
			if b, err := os.ReadFile(filepath.Join(m.Dir, name)); err == nil {
				m.Text = string(b)
				m.License = Classify(m.Text)
				break
			}
		}
		mods = append(mods, m)
	}
	// the standard library is BSD-3-Clause and is not a module
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods, nil
}

// Notice renders the NOTICE file: every linked module with its licence and full licence text.
func Notice(mods []Module) string {
	var b strings.Builder
	b.WriteString("Tasklane includes the following third-party software. Each component is distributed under its own licence.\n")
	b.WriteString("This file is generated by `make notice`; do not edit by hand.\n\n")
	b.WriteString("The Go standard library and runtime (BSD-3-Clause), https://go.dev/LICENSE\n")
	for _, m := range mods {
		fmt.Fprintf(&b, "\n================================================================================\n%s %s\nLicence: %s\n--------------------------------------------------------------------------------\n%s\n", m.Path, m.Version, m.License, strings.TrimSpace(m.Text))
	}
	return b.String()
}

// SBOM is a plain module list in a stable format (an SPDX document is produced by the release pipeline).
func SBOM(mods []Module) string {
	var b strings.Builder
	for _, m := range mods {
		fmt.Fprintf(&b, "%s %s %s\n", m.Path, m.Version, m.License)
	}
	return b.String()
}

